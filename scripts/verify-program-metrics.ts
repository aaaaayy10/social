import assert from 'node:assert/strict';
import {attendance,calculateAttendance,summarizeAttendance,validateAttendance,verifiedAttendance} from '../src/lib/attendance-analysis';
import {programMetrics,currentEnrollment} from '../src/lib/program-metrics';
import evidence from '../src/data/attendance-expectations.json';
validateAttendance();
const all=attendance.records.map(calculateAttendance),summary=summarizeAttendance(attendance.records);
assert.equal(all.length,450);assert.equal(summary.attended,42874);assert.equal(summary.sessions,1861);
assert.equal(summary.verifiedCount,96);assert.equal(summary.pendingCount,263);assert.equal(summary.expected,14274);
assert.equal(programMetrics.currentPaidUnique,763);assert.equal(programMetrics.totals.paid,1309);assert.equal(programMetrics.totals.applications,1318);assert.equal(programMetrics.cumulativeUnique,1064);
assert.equal(currentEnrollment('난타초급')?.paid,32);
assert.ok(all.every(r=>r.attendanceRate===null||(r.attendanceRate>=0&&r.attendanceRate<=100)));
assert.ok(all.filter(r=>r.verification==='pending').every(r=>r.expected===null&&r.absent===null&&r.attendanceRate===null&&r.absenceRate===null));
assert.ok(all.filter(r=>r.month==='2026-01').every(r=>r.verification==='closed'&&r.expected===0&&r.absent===0&&r.attendanceRate===null));
assert.equal(all.filter(r=>r.sourceType==='rf').reduce((s,r)=>s+(r.attended??0),0),19178);
assert.equal(all.filter(r=>r.sourceType==='manual').reduce((s,r)=>s+(r.attended??0),0),23696);
const verified=all.filter(r=>r.verification==='verified');
const verifiedActual=verified.reduce((s,r)=>s+(r.attended??0),0);
assert.equal(summary.attendanceRate,verifiedActual/14274*100);
assert.equal(summary.absent,14274-verifiedActual);
assert.ok(Math.abs((summary.attendanceRate??0)+(summary.absenceRate??0)-100)<1e-10);
const mixed=summarizeAttendance([attendance.records.find(r=>calculateAttendance(r).verification==='verified')!,attendance.records.find(r=>calculateAttendance(r).verification==='pending')!]);
assert.equal(mixed.verifiedCount,1);assert.equal(mixed.pendingCount,1);assert.ok((mixed.attendanceRate??999)<=100);
assert.throws(()=>verifiedAttendance(11,1,{month:'2026-10',programCode:'test',expected:10,sessions:1,source:'test',verifiedOn:'2026-11-04'}));
assert.throws(()=>verifiedAttendance(8,2,{month:'2026-10',programCode:'test',expected:10,sessions:1,source:'test',verifiedOn:'2026-11-04'}));
assert.equal(verifiedAttendance(8,1,{month:'2026-10',programCode:'test',expected:10,sessions:1,source:'test',verifiedOn:'2026-11-04'}).absenceRate,20);
assert.equal(evidence.records.length,96);
console.log(JSON.stringify({records:all.length,summary,rf:19178,manual:23696,paid:1309,currentPaidUnique:763,cumulative:1064}));
